"""Machine-readable and markdown reports for eval gate runs.

Used by `cortexops eval run --output-json/--summary-md` and for GitHub Actions
job summaries (`GITHUB_STEP_SUMMARY`).
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from .models import EvalSummary, ThresholdResult

REPORT_SCHEMA_VERSION = 1
DEFAULT_FAIL_ON = "pass_rate < 1.0"
MAX_FAILED_CASES = 50
_DETAIL_CHARS = 160


def pass_rate(summary: EvalSummary) -> float:
    return summary.passed / max(summary.total_cases, 1)


def mean_score(summary: EvalSummary) -> float:
    """Mean case score, 0-100."""
    scores = [r.score for r in summary.case_results]
    return sum(scores) / len(scores) if scores else 0.0


def gate_passed(thresholds: list[ThresholdResult]) -> bool:
    return not any(t.failed for t in thresholds)


def build_report(
    summary: EvalSummary,
    thresholds: list[ThresholdResult],
    *,
    dataset: str | None = None,
) -> dict[str, Any]:
    """JSON-serialisable report: the EvalSummary fields (without traces) plus gate results."""
    from . import __version__

    data = summary.model_dump(mode="json")
    for case in data.get("case_results", []):
        case.pop("trace", None)
    return {
        "schema_version": REPORT_SCHEMA_VERSION,
        "cortexops_version": __version__,
        "gate_passed": gate_passed(thresholds),
        "dataset_path": dataset,
        "pass_rate": pass_rate(summary),
        "mean_score": mean_score(summary),
        "thresholds": [t.model_dump(mode="json") for t in thresholds],
        **data,
    }


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _ms(value: float) -> str:
    return f"{value:.0f} ms" if value >= 10 else f"{value:.1f} ms"


def _cell(text: Any) -> str:
    s = " ".join(str(text).split())
    if len(s) > _DETAIL_CHARS:
        s = s[: _DETAIL_CHARS - 3] + "..."
    return s.replace("|", "\\|")


def render_markdown(
    summary: EvalSummary,
    thresholds: list[ThresholdResult],
    *,
    dataset: str | None = None,
    title: str = "CortexOps eval gate",
    max_failed_cases: int = MAX_FAILED_CASES,
) -> str:
    """Render a GitHub-flavoured markdown report for a job summary or PR comment."""
    from . import __version__

    passed = gate_passed(thresholds)
    lines = [f"## {title}: {'PASSED' if passed else 'FAILED'}", ""]

    context = [f"Project `{summary.project}`"]
    if dataset:
        context.append(f"dataset `{dataset}` (v{summary.dataset_version})")
    context.append(f"run `{summary.run_id[:8]}`")
    lines += [", ".join(context), ""]

    lines += [
        "| Metric | Value |",
        "|---|---|",
        f"| Cases | {summary.total_cases} |",
        f"| Passed / failed | {summary.passed} / {summary.failed} |",
        f"| Pass rate | {_pct(pass_rate(summary))} |",
        f"| Mean score | {mean_score(summary):.1f}/100 |",
        f"| Task completion | {_pct(summary.task_completion_rate)} |",
        f"| Tool accuracy | {_pct(summary.tool_accuracy / 100.0)} |",
        f"| Latency p50 / p95 | {_ms(summary.latency_p50_ms)} / {_ms(summary.latency_p95_ms)} |",
        "",
    ]

    if thresholds:
        lines += [
            "### Thresholds",
            "",
            "The gate fails when any condition below is true.",
            "",
            "| Fail on | Actual | Result |",
            "|---|---|---|",
        ]
        for t in thresholds:
            lines.append(f"| `{_cell(t.expression)}` | {t.actual:.3f} | {'FAILED' if t.failed else 'ok'} |")
        lines.append("")

    failing = [r for r in summary.case_results if not r.passed]
    if failing:
        lines += [
            f"### Failed cases ({len(failing)})",
            "",
            "| Case | Failure kind | Score | Detail |",
            "|---|---|---|---|",
        ]
        for r in failing[:max_failed_cases]:
            kind = r.failure_kind.value if r.failure_kind else "unknown"
            detail = _cell(r.failure_detail) if r.failure_detail else ""
            lines.append(f"| `{_cell(r.case_id)}` | {kind} | {r.score:.0f} | {detail} |")
        if len(failing) > max_failed_cases:
            lines.append(f"\n_...and {len(failing) - max_failed_cases} more failed cases._")
        lines.append("")
    else:
        lines += ["_All cases passed._", ""]

    lines.append(f"<sub>Generated by cortexops {__version__}</sub>")
    return "\n".join(lines) + "\n"


def render_junit(summary: EvalSummary, thresholds: list[ThresholdResult]) -> str:
    """JUnit XML: one testcase per eval case plus one per fail_on condition."""
    import xml.etree.ElementTree as ET

    root = ET.Element("testsuites", name="cortexops")
    cases = ET.SubElement(
        root, "testsuite", name=f"cortexops.{summary.project}", tests=str(summary.total_cases),
        failures=str(summary.failed), errors="0",
        time=f"{sum(r.latency_ms for r in summary.case_results) / 1000:.3f}",
    )
    for r in summary.case_results:
        tc = ET.SubElement(
            cases, "testcase", classname=f"cortexops.{summary.project}", name=r.case_id,
            time=f"{r.latency_ms / 1000:.3f}",
        )
        if not r.passed:
            kind = r.failure_kind.value if r.failure_kind else "unknown"
            failure = ET.SubElement(tc, "failure", type=kind, message=f"score {r.score:.0f}: {kind}")
            failure.text = r.failure_detail or ""

    gate = ET.SubElement(
        root, "testsuite", name="cortexops.thresholds", tests=str(len(thresholds)),
        failures=str(sum(t.failed for t in thresholds)), errors="0", time="0",
    )
    for t in thresholds:
        tc = ET.SubElement(gate, "testcase", classname="cortexops.thresholds", name=f"fail_on: {t.expression}", time="0")
        if t.failed:
            ET.SubElement(tc, "failure", type="threshold", message=f"{t.metric}={t.actual:.3f} {t.op} {t.threshold}")

    root.set("tests", str(summary.total_cases + len(thresholds)))
    root.set("failures", str(summary.failed + sum(t.failed for t in thresholds)))
    ET.indent(root)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def append_step_summary(markdown: str, path: str | None = None) -> Path | None:
    """Append markdown to the GitHub Actions job summary; no-op outside Actions."""
    target = path or os.getenv("GITHUB_STEP_SUMMARY")
    if not target:
        return None
    out = Path(target)
    with out.open("a", encoding="utf-8") as fh:
        fh.write(markdown)
        fh.write("\n")
    return out
